"""
InvariantLens - Seeded Message Bus & Scheduler
Deterministic event delivery with controllable ordering, delays, duplicates, drops.
"""

from __future__ import annotations
import random
from dataclasses import dataclass, field
from typing import Any, Callable
from collections import defaultdict
from simulator.event_schema import Event, Service, EventType, CAUSAL_PARENT_RULES, EMITTER_SERVICE


@dataclass
class ScheduledDelivery:
    """A message scheduled for delivery"""
    event: Event
    target_service: Service
    deliver_at_seq: int  # scheduler sequence number when this should be delivered


class MessageBus:
    """
    In-process message bus with seeded scheduler controlling:
    - Delivery order
    - Delays
    - Duplicates
    - Drops
    
    All randomness controlled by a single seed for deterministic replay.
    """

    def __init__(self, seed: int = 42, fault_config: dict | None = None):
        self.seed = seed
        self.rng = random.Random(seed)
        self.fault_config = fault_config or {}
        
        # Service handlers: service -> list of (event_type, handler_fn)
        self.handlers: dict[Service, list[tuple[EventType, Callable]]] = defaultdict(list)
        
        # Pending deliveries sorted by deliver_at_seq
        self.pending_deliveries: list[ScheduledDelivery] = []
        
        # Delivered events per trace (for causal parent tracking)
        self.delivered_events: dict[str, list[Event]] = defaultdict(list)
        
        # Scheduler state
        self.delivery_seq = 0
        self.service_clocks: dict[Service, int] = defaultdict(int)
        self.trace_clocks: dict[str, int] = defaultdict(int)
        
        # Fault injection state
        self.dropped_events: list[Event] = []
        self.duplicated_events: list[Event] = []
        
        # Metrics
        self.total_sent = 0
        self.total_delivered = 0
        self.total_dropped = 0
        self.total_duplicated = 0

    def register_handler(self, service: Service, event_type: EventType, handler: Callable):
        """Register a handler for a specific event type on a service"""
        self.handlers[service].append((event_type, handler))

    def emit(self, event: Event) -> list[Event]:
        """
        Emit an event from a service. Returns any new events generated by handlers.
        This is called by service code to send events.
        """
        self.total_sent += 1
        
        # Determine target services based on event type
        target_services = self._get_target_services(event.type)
        
        # If no target services (terminal event), record it directly
        if not target_services:
            self.delivery_seq += 1
            event.delivery_seq = self.delivery_seq
            trace_events = self.delivered_events[event.trace_id]
            if not any(e.event_id == event.event_id for e in trace_events):
                trace_events.append(event)
            self.total_delivered += 1
            return []
        
        # Schedule delivery to each target service (create copy for each)
        for target_service in target_services:
            # Create a copy of the event for this delivery
            event_copy = event.model_copy()
            delivery = ScheduledDelivery(
                event=event_copy,
                target_service=target_service,
                deliver_at_seq=self.delivery_seq + len(self.pending_deliveries) + 1
            )
            self.pending_deliveries.append(delivery)
        
        # Sort by delivery sequence
        self.pending_deliveries.sort(key=lambda d: d.deliver_at_seq)
        
        return []

    def _get_target_services(self, event_type: EventType) -> list[Service]:
        """Determine which services consume this event type"""
        # Based on the workflow: Orders -> Payments, Inventory
        # Payments -> Orders (for confirmation/refund)
        # Inventory -> Orders (for confirmation)
        consumers = {
            EventType.ORDER_PLACED: [Service.PAYMENTS, Service.INVENTORY],
            EventType.PAYMENT_CAPTURED: [Service.ORDERS],
            EventType.PAYMENT_FAILED: [Service.ORDERS],
            EventType.REFUND_PAYMENT: [Service.ORDERS],
            EventType.INVENTORY_RESERVED: [Service.ORDERS],
            EventType.INVENTORY_REJECTED: [Service.ORDERS, Service.PAYMENTS],  # Payments needs to know for refund
            EventType.INVENTORY_RELEASED: [Service.ORDERS],
            EventType.ORDER_CONFIRMED: [],  # Terminal
            EventType.ORDER_FAILED: [],  # Terminal
        }
        return consumers.get(event_type, [])

    def step(self) -> list[Event]:
        """
        Execute one scheduler step: deliver the next pending message.
        Returns any new events generated by handlers.
        """
        if not self.pending_deliveries:
            return []
        
        # Get next delivery
        delivery = self.pending_deliveries.pop(0)
        event = delivery.event
        target_service = delivery.target_service
        
        self.delivery_seq += 1
        event.delivery_seq = self.delivery_seq
        
        # Apply fault injection
        if self._should_drop(event):
            self.dropped_events.append(event)
            self.total_dropped += 1
            return []
        
        if self._should_duplicate(event):
            # Create a duplicate delivery
            duplicate = ScheduledDelivery(
                event=event.model_copy(),
                target_service=target_service,
                deliver_at_seq=self.delivery_seq + 1  # Deliver immediately after
            )
            self.pending_deliveries.insert(0, duplicate)
            self.duplicated_events.append(event)
            self.total_duplicated += 1
        
        # Update logical clocks
        self._update_clocks(event, target_service)
        
        # Deliver to handlers
        new_events = self._deliver_to_handlers(event, target_service)
        
        # Record as delivered (only once per trace per event_id)
        trace_events = self.delivered_events[event.trace_id]
        if not any(e.event_id == event.event_id for e in trace_events):
            trace_events.append(event)
        self.total_delivered += 1
        
        # Schedule any new events
        for new_event in new_events:
            self.emit(new_event)
        
        return new_events

    def _should_drop(self, event: Event) -> bool:
        """Check if this event should be dropped based on fault config"""
        drop_rate = self.fault_config.get("drop_rate", 0.0)
        if drop_rate <= 0:
            return False
        # Drop based on event ID for determinism
        return self.rng.random() < drop_rate

    def _should_duplicate(self, event: Event) -> bool:
        """Check if this event should be duplicated"""
        dup_rate = self.fault_config.get("duplicate_rate", 0.0)
        if dup_rate <= 0:
            return False
        return self.rng.random() < dup_rate

    def _update_clocks(self, event: Event, target_service: Service):
        """Update Lamport clocks on delivery"""
        # Service clock
        self.service_clocks[target_service] = max(
            self.service_clocks[target_service], event.logical_clock
        ) + 1
        
        # Trace clock
        self.trace_clocks[event.trace_id] = max(
            self.trace_clocks[event.trace_id], event.logical_clock
        ) + 1

    def _deliver_to_handlers(self, event: Event, target_service: Service) -> list[Event]:
        """Deliver event to registered handlers for the target service"""
        new_events = []
        for event_type, handler in self.handlers[target_service]:
            if event.type == event_type:
                try:
                    result = handler(event)
                    if result:
                        if isinstance(result, list):
                            new_events.extend(result)
                        else:
                            new_events.append(result)
                except Exception as e:
                    # Handler error - in real system this would be logged
                    # For simulator, we let it propagate
                    raise
        return new_events

    def run_until_quiescence(self, max_steps: int = 10000) -> list[Event]:
        """
        Run the scheduler until no pending deliveries or max steps reached.
        Returns all events that were delivered.
        """
        all_events = []
        steps = 0
        
        while self.pending_deliveries and steps < max_steps:
            new_events = self.step()
            all_events.extend(new_events)
            steps += 1
        
        if steps >= max_steps:
            print(f"Warning: Scheduler reached max steps ({max_steps})")
        
        return all_events

    def get_trace_events(self, trace_id: str) -> list[Event]:
        """Get all delivered events for a trace, sorted by delivery_seq"""
        events = self.delivered_events.get(trace_id, [])
        return sorted(events, key=lambda e: e.delivery_seq)

    def is_trace_closed(self, trace_id: str) -> bool:
        """Check if a trace has reached terminal state or scheduler quiescence"""
        events = self.get_trace_events(trace_id)
        if not events:
            return False
        
        # Check for terminal events
        last_event = events[-1]
        if last_event.type in (EventType.ORDER_CONFIRMED, EventType.ORDER_FAILED):
            return True
        
        # Check scheduler quiescence (no pending messages for this trace)
        for delivery in self.pending_deliveries:
            if delivery.event.trace_id == trace_id:
                return False
        
        return True

    def get_stats(self) -> dict:
        return {
            "total_sent": self.total_sent,
            "total_delivered": self.total_delivered,
            "total_dropped": self.total_dropped,
            "total_duplicated": self.total_duplicated,
            "pending_deliveries": len(self.pending_deliveries),
            "traces_active": len(self.delivered_events),
        }


def create_event(
    trace_id: str,
    event_type: EventType,
    payload: dict,
    causal_parents: list[str] | None = None,
    sku: str | None = None,
    logical_clock: int | None = None,
) -> Event:
    """Factory function to create properly formed events"""
    service = EMITTER_SERVICE[event_type]
    
    # Determine logical clock
    if logical_clock is None:
        logical_clock = 1  # Will be updated by bus
    
    # Determine causal parents from rules if not provided
    if causal_parents is None:
        causal_parents = []
        required_parents = CAUSAL_PARENT_RULES.get(event_type, [])
        # In practice, the bus will fill these in based on delivered events
    
    return Event(
        trace_id=trace_id,
        stream_keys=StreamKeys(order_id=trace_id, sku=sku),
        service=service,
        type=event_type,
        logical_clock=logical_clock,
        causal_parent_ids=causal_parents or [],
        payload=payload,
    )


